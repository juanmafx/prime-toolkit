import hashlib
import json
import os
import platform
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
REPORT_DIRECTORY = ROOT / "reports" / "tests"
DIGEST_ROOTS = ("src", "tests", "javascript/src", "javascript/test", "db")


def source_digest() -> str:
    digest = hashlib.sha256()
    for directory in DIGEST_ROOTS:
        for path in sorted((ROOT / directory).rglob("*")):
            if path.is_file() and "__pycache__" not in path.parts:
                digest.update(path.relative_to(ROOT).as_posix().encode())
                digest.update(path.read_bytes())
    return digest.hexdigest()


def summarize_junit(path: Path) -> dict[str, int]:
    cases = list(ET.parse(path).getroot().iter("testcase"))
    failed = sum(
        1 for case in cases if case.find("failure") is not None or case.find("error") is not None
    )
    skipped = sum(1 for case in cases if case.find("skipped") is not None)
    return {
        "total": len(cases),
        "passed": len(cases) - failed - skipped,
        "failed": failed,
        "skipped": skipped,
    }


def run_python_suite(workspace: Path) -> tuple[int, dict[str, int], dict[str, float]]:
    junit = workspace / "python.xml"
    coverage = workspace / "coverage.json"
    completed = subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            "-q",
            "-p",
            "no:cacheprovider",
            f"--junitxml={junit}",
            "--cov=prime_maker",
            f"--cov-report=json:{coverage}",
        ],
        cwd=ROOT,
        env={"COVERAGE_FILE": str(workspace / ".coverage"), "PATH": os.environ.get("PATH", "")},
        check=False,
    )
    totals = json.loads(coverage.read_text(encoding="utf-8"))["totals"]
    measured = {
        "line_and_branch_percent": round(totals["percent_covered"], 2),
    }
    return completed.returncode, summarize_junit(junit), measured


def run_javascript_suite(workspace: Path) -> tuple[int, dict[str, int], str]:
    junit = workspace / "javascript.xml"
    completed = subprocess.run(
        [
            "node",
            "--test",
            "--test-reporter=junit",
            f"--test-reporter-destination={junit}",
            "test/**/*.test.js",
        ],
        cwd=ROOT / "javascript",
        check=False,
    )
    version = subprocess.run(
        ["node", "--version"], capture_output=True, text=True, check=True
    ).stdout.strip()
    return completed.returncode, summarize_junit(junit), version


def render_markdown(report: dict[str, Any]) -> str:
    python = report["python"]
    javascript = report["javascript"]
    return "\n".join(
        [
            "# Test Report",
            "",
            "Generated by `scripts/generate_test_report.py` from an actual local run.",
            "",
            f"- Run at (UTC): {report['generated_at']}",
            f"- Source digest (SHA-256): `{report['source_digest']}`",
            f"- Overall result: **{report['result']}**",
            "",
            "| Suite | Runtime | Total | Passed | Failed | Skipped |",
            "| --- | --- | ---: | ---: | ---: | ---: |",
            f"| Python | CPython {python['runtime']} | {python['total']} | {python['passed']} "
            f"| {python['failed']} | {python['skipped']} |",
            f"| JavaScript | Node.js {javascript['runtime']} | {javascript['total']} "
            f"| {javascript['passed']} | {javascript['failed']} | {javascript['skipped']} |",
            "",
            "Measured Python line and branch coverage: "
            f"{python['coverage']['line_and_branch_percent']}%.",
            "",
        ]
    )


def main() -> int:
    REPORT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as directory:
        workspace = Path(directory)
        python_code, python_summary, coverage = run_python_suite(workspace)
        node_code, node_summary, node_version = run_javascript_suite(workspace)
    success = python_code == 0 and node_code == 0
    report: dict[str, Any] = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "source_digest": source_digest(),
        "result": "passed" if success else "failed",
        "python": {
            "runtime": platform.python_version(),
            **python_summary,
            "coverage": coverage,
        },
        "javascript": {"runtime": node_version.removeprefix("v"), **node_summary},
    }
    (REPORT_DIRECTORY / "latest.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )
    (REPORT_DIRECTORY / "latest.md").write_text(render_markdown(report), encoding="utf-8")
    return 0 if success else 1


if __name__ == "__main__":
    raise SystemExit(main())
